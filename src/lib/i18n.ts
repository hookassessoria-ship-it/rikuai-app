const DICTS: Record<SupportedLocale, Dict> = {
  "pt-BR": PT,
  "en-US": EN,
  "es-ES": es,
  "es-MX": es,
  "fr-FR": fr,
  "de-DE": de,
  "it-IT": it,
  "ja-JP": ja,
};

let _lang: SupportedLocale = "pt-BR";
const _listeners = new Set<() => void>();

export function setLanguage(lang: SupportedLocale, currency?: SupportedCurrency) {
  _lang = lang;
  setFormattingPrefs(lang, currency ?? "BRL");
  _listeners.forEach((l) => l());
}

export function getLanguage(): SupportedLocale { return _lang; }

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[_lang] ?? PT;
  let out = dict[key] ?? EN[key] ?? PT[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}

function subscribe(listener: () => void) {
  _listeners.add(listener);
  return () => _listeners.delete(listener);
}

export function useT() {
  useSyncExternalStore(subscribe, getLanguage, getLanguage);
  return t;
}

